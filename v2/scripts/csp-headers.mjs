// Generates dist/_headers with a strict Content-Security-Policy.
// Usage (from v2/, after `astro build`):  node scripts/csp-headers.mjs [distDir]
//
// Every inline executable <script> found in dist/**/*.html is allow-listed by
// its sha256 hash, so script-src needs no 'unsafe-inline'. Style attributes are
// used throughout the site, so style-src keeps 'unsafe-inline'.
// This is the ONLY place the CSP is defined: do not also set a
// Content-Security-Policy header in netlify.toml (two CSP headers intersect).
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const HCAPTCHA = ['https://hcaptcha.com', 'https://*.hcaptcha.com'];
// web3forms.com/client/script.js loads the hCaptcha API (js.hcaptcha.com) and
// nothing else for a plain contact form (file-upload widgets are not used).
const WEB3FORMS_SCRIPT = 'https://web3forms.com';

const JS_TYPES = new Set(['', 'module', 'text/javascript', 'application/javascript', 'text/ecmascript', 'application/ecmascript']);

export const walkHtml = (dir, out = []) => {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) walkHtml(p, out);
    else if (e.name.endsWith('.html')) out.push(p);
  }
  return out;
};

/** Inline executable scripts in an HTML string: [{ text, hash }]. */
export const inlineScripts = (html) => {
  const found = [];
  const re = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;
  let m;
  while ((m = re.exec(html))) {
    const attrs = m[1];
    if (/\bsrc\s*=/i.test(attrs)) continue;
    const type = (/\btype\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i.exec(attrs) || [])
      .slice(1)
      .find((v) => v !== undefined);
    if (!JS_TYPES.has((type ?? '').trim().toLowerCase())) continue;
    if (!m[2].trim()) continue;
    found.push({ text: m[2], hash: `'sha256-${createHash('sha256').update(m[2], 'utf8').digest('base64')}'` });
  }
  return found;
};

export const buildPolicy = (hashes) =>
  [
    `default-src 'self'`,
    `script-src ${["'self'", ...hashes, WEB3FORMS_SCRIPT, ...HCAPTCHA].join(' ')}`,
    `style-src ${["'self'", "'unsafe-inline'", ...HCAPTCHA].join(' ')}`,
    `img-src 'self' data:`,
    `font-src 'self'`,
    `connect-src ${["'self'", ...HCAPTCHA].join(' ')}`,
    `frame-src ${HCAPTCHA.join(' ')}`,
    `form-action 'self' https://api.web3forms.com`,
    `frame-ancestors 'none'`,
    `base-uri 'self'`,
    `object-src 'none'`,
    `upgrade-insecure-requests`,
  ].join('; ');

const main = () => {
  const dist = resolve(process.argv[2] || 'dist');
  if (!existsSync(dist)) {
    console.error(`csp-headers: dist not found: ${dist}`);
    process.exit(1);
  }
  const hashes = new Set();
  const pages = walkHtml(dist);
  for (const f of pages) for (const s of inlineScripts(readFileSync(f, 'utf8'))) hashes.add(s.hash);
  const policy = buildPolicy([...hashes].sort());
  const out =
    '# Generated by scripts/csp-headers.mjs after `astro build`. Do not edit.\n' +
    `/*\n  Content-Security-Policy: ${policy}\n`;
  writeFileSync(join(dist, '_headers'), out);
  console.log(`csp-headers: ${pages.length} pages, ${hashes.size} unique inline-script hashes, policy ${policy.length} chars -> ${join(dist, '_headers')}`);
};

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
